#!/usr/bin/env python3
"""Build the per-screen static mockups for the v2 reskin.

Static HTML on purpose: no JS, no API, no app.js. These exist to check layout
and iconography against reference-images/ before any of it is committed to
app.js, and they must open over file:// as readily as over a static server.

Icons are read from static-v2/icons.js rather than re-derived here, so the
mockups and the eventual app cannot drift apart: if a slot is remapped, this
regenerates against the same map the application will use.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'datum_sync' / 'static-v2'

ICONS = json.loads(
    re.search(r'export const ICONS = (\{.*?\});',
              (OUT / 'icons.js').read_text(), re.S).group(1))


# The brand mark is inlined rather than <img src>'d so it inherits the dark
# zone's currentColor and still renders over file://. The viewBox is read
# from the file rather than repeated here: it moves whenever the wordmark is
# refitted, and a stale copy would silently crop or letterbox the mark.
_mark = (OUT / 'datum-mark.svg').read_text().strip()
BRAND_VIEWBOX = re.search(r'<svg[^>]*viewBox="([^"]+)"', _mark).group(1)
BRAND_MARK = re.sub(r'^.*?<svg[^>]*>|</svg>\s*$', '', _mark, flags=re.S).strip()


def ico(name, size=17, cls=''):
    if name not in ICONS:
        raise KeyError(f'no icon slot {name!r} — add it to tools/gen_icons.py')
    c = f' class="{cls}"' if cls else ''
    return (f'<svg{c} width="{size}" height="{size}" viewBox="0 0 256 256" '
            f'fill="currentColor" aria-hidden="true">{ICONS[name]}</svg>')


