# ── Variations explorer ──────────────────────────────────────────────────
# The only page here that carries JS, and deliberately so: type scale and
# link colour are comparative judgements, and flipping one control on a live
# screen shows far more than a row of static screenshots. It overrides
# tokens on :root only -- it does not fork style.css, so whatever is chosen
# transfers as a one-line edit.

# The first entry of each list is the option now baked into style.css, so the
# page opens on the shipped design and every other radio reads as a departure
# from it. Keep it that way when adding options.

# Contrast measured against white #ffffff (light zone --panel).
LINK_OPTIONS = [
    ('#1D3A5C', 'Navy (shipped)', '11.59:1'),
    ('#0d0d0c', 'Near-black',     '19.44:1'),
    ('#2C5480', 'Navy, lifted',    '7.82:1'),
    ('#6E4E17', 'Amber, deepened', '7.59:1'),
    ('#8A6420', 'Amber, darkened', '5.35:1'),
    ('#C89632', 'Amber',           '2.67:1  FAILS AA'),
]

# Raising the root alone does not get there: at 16px the h1 reaches only
# 24.8px against Flow's ~40, and the row pitch 65 against 78, because
# `h1: 1.55rem` and `td: .75rem` are the binding constraints, not the root.
# So each option bundles root + heading scale + table density.
# Fields: label, root, h1, h2, h3, td padding, note.
TYPE_OPTIONS = [
    ('Flow-matched','16px', '2.5rem',  '1.375rem', '1.125rem','1.15rem','h1 40px, shipped'),
    ('Comfortable', '16px', '2rem',    '1.25rem',  '1.05rem', '1rem',   'h1 32px'),
    ('Root only',   '16px', '1.55rem', '1.1rem',   '.95rem',  '.75rem', 'h1 24.8px'),
    ('Original',    '14px', '1.55rem', '1.1rem',   '.95rem',  '.75rem', 'h1 21.7px'),
]


def screen_variants():
    def radios(name, opts):
        return '\n'.join(
            f'<label><input type="radio" name="{name}" value="{v}"'
            f'{" checked" if i == 0 else ""}><span>{lbl}</span>'
            f'<em>{note}</em></label>'
            for i, (v, lbl, note) in enumerate(opts))

    type_radios = '\n'.join(
        f'<label><input type="radio" name="type" value="{i}"'
        f'{" checked" if i == 0 else ""}><span>{lbl}</span><em>{note}</em></label>'
        for i, (lbl, *_, note) in enumerate(TYPE_OPTIONS))
    type_css = json.dumps([
        f'html,body{{font-size:{r}}} h1{{font-size:{h1}}} h2{{font-size:{h2}}} '
        f'h3{{font-size:{h3}}} td{{padding:{td}}} th{{padding-left:{td};padding-right:{td}}}'
        for _, r, h1, h2, h3, td, _n in TYPE_OPTIONS])

    body = screen_repositories()
    body = body[body.index('<main class="view"'):body.index('</main>') + 7]

    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Mock &mdash; Variations</title>
<link rel="stylesheet" href="style.css">
<style>
.vbar {{ position: sticky; top: 0; z-index: 9; display: flex; gap: 2.5rem;
  flex-wrap: wrap; padding: 12px 16px; background: #16232F; color: #E8EEF4;
  font: 12px/1.4 system-ui, sans-serif; }}
.vbar section {{ display: flex; gap: .5rem; align-items: center; }}
.vbar h4 {{ margin: 0 .5rem 0 0; font: 600 11px/1 system-ui; letter-spacing: .08em;
  text-transform: uppercase; color: #8FA3B5; }}
.vbar label {{ display: flex; align-items: center; gap: .3rem; cursor: pointer;
  padding: .25rem .45rem; border-radius: 4px; }}
.vbar label:hover {{ background: #1B2C3D; }}
.vbar em {{ font-style: normal; color: #8FA3B5; font-size: 10px; }}
.frame {{ height: calc(100vh - 46px); }}
.frame .app {{ height: 100%; }}
</style>
</head>
<body>

<!-- Generated by tools/gen_mockups.py. Do not hand-edit: regenerate. -->

<div class="vbar">
  <section><h4>Link colour</h4>{radios('link', LINK_OPTIONS)}</section>
  <section><h4>Type scale</h4>{type_radios}</section>
</div>

<div class="frame">
<div id="app" class="app">
  <div class="brand">
    <button type="button" aria-label="Collapse navigation">{ico('nav-toggle', 18)}</button>
    <svg class="brand-name brand-mark" height="26" viewBox="{BRAND_VIEWBOX}"
         fill="none" role="img" aria-label="Datum">{BRAND_MARK}</svg>
  </div>
  <header class="topbar">
    <div class="engines">{ico('engine', 15)} <b>2</b> engines &middot; <b>0</b> running</div>
    <div class="tb-right">
      <button type="button" class="tb-icon" aria-label="Notifications">{ico('notifications', 18)}</button>
      <div class="tb-user"><button type="button" class="tb-avatar">MR</button></div>
    </div>
  </header>
  <nav class="sidebar">
{chr(10).join(f'      <a href="#"{" class=" + chr(34) + "active" + chr(34) if s == "repositories" else ""}>{ico(s)}<span class="nav-label">{l}</span></a>' for s, l in NAV)}
    <div class="nav-group-label">Admin</div>
{chr(10).join(f'      <a href="#">{ico(s)}<span class="nav-label">{l}</span></a>' for s, l in NAV_ADMIN)}
  </nav>
{body}
</div>
</div>

<script>
// Overrides land on :root. --link is redeclared inside .topbar/.view, so a
// :root override alone would lose to that; the light-zone rule is restated
// at higher specificity via a stylesheet rather than an inline style.
const TYPE = {type_css};
const sheet = document.head.appendChild(document.createElement('style'));
function apply() {{
  const link = document.querySelector('[name=link]:checked').value;
  const type = TYPE[document.querySelector('[name=type]:checked').value];
  sheet.textContent = `.topbar, .view {{ --link: ${{link}}; }} ` + type;
}}
document.querySelectorAll('.vbar input').forEach(i =>
    i.addEventListener('change', apply));
apply();
</script>
</body>
</html>
'''


SCREENS = {
    'mock-variants.html': screen_variants,
    'mock-repositories.html': screen_repositories,
    'mock-jobs.html': screen_jobs,
    'mock-connections.html': screen_connections,
    'mock-run-workspace.html': screen_run_workspace,
}


def main():
    for fname, fn in SCREENS.items():
        OUT.joinpath(fname).write_text(fn())
        print('wrote', fname)


if __name__ == '__main__':
    main()
